# d3d9shim_ops.h
# --------------------------------------------------------------------------

def emit_ops_h():
    o = [BANNER % "d3d9shim_ops.h -- the D3D9 shim wire format, both sides"]
    o.append("""#ifndef __MADEIRA_D3D9SHIM_OPS_H
#define __MADEIRA_D3D9SHIM_OPS_H

#include <stddef.h>
#include <stdint.h>

#include <windows.h>
#include <d3d9.h>

/* Every parameter-block field is fixed width, so ONE struct definition is
 * correct on i386 and on LP64 and there is no *_params32 mirror: the
 * winemetal WMTMemoryPointer trick (winemetal.h:132-200) applied to the whole
 * block.  Guest pointers are uint32_t, handles and native object references
 * uint64_t, and the 64-bit fields are emitted FIRST so each one lands on a
 * multiple of 8 whatever the target's alignment rule for 64-bit types is.
 *
 * The consequence, and the reason d3d9_unix_table.c can point both tables at
 * the same functions: a block can only ever be written by a 32-bit caller,
 * because a 64-bit pointer does not fit in it.  There is exactly one correct
 * reading of a block, so there is nothing for a _32 variant to do
 * differently.  _d3d9_init refuses a caller whose pointer width is not 4
 * rather than pretending otherwise (WOW64_DESIGN.md 7.4 rule 4). */
""")
    o.append("#define D3D9SHIM_API_VERSION %du" % api.API_VERSION)
    o.append("#define D3D9SHIM_API_HASH 0x%016xull" % api.api_hash())
    o.append("#define D3D9SHIM_OP_COUNT %du\n" % len(OPS))

    o.append("enum d3d9shim_op {")
    for i, (name, it, m) in enumerate(OPS):
        if is_transport(it, m) and i == TRANSPORT_BASE:
            o.append("    /* The TRANSPORT slots: not vtable methods, so no")
            o.append("     * interface in the description produces them.  They")
            o.append("     * come after the whole generated range, which is what")
            o.append("     * fixes their numbers at %d.. and leaves every"
                     % TRANSPORT_BASE)
            o.append("     * generated slot -- the slot number IS the ABI --")
            o.append("     * exactly where it was. */")
        o.append("    %-56s = %3d," % (name, i))
    o.append("    D3D9OP_COUNT_ = %d" % len(OPS))
    o.append("};\n")

    o.append("""/* _d3d9_init status codes. */
enum d3d9shim_init_status {
    D3D9SHIM_INIT_OK = 0,
    D3D9SHIM_INIT_HASH_MISMATCH = 1,
    D3D9SHIM_INIT_BAD_PTR_SIZE = 2,
    D3D9SHIM_INIT_NATIVE_FAILED = 3
};

struct d3d9_init_params {
    uint64_t api_hash;       /* IN:  the shim's D3D9SHIM_API_HASH */
    uint64_t native_hash;    /* OUT: the native side's, on a mismatch */
    uint32_t api_version;    /* IN:  D3D9SHIM_API_VERSION */
    uint32_t ptr_size;       /* IN:  sizeof(void *) in the calling module */
    uint32_t op_count;       /* IN:  D3D9SHIM_OP_COUNT */
    uint32_t status;         /* OUT: enum d3d9shim_init_status */
};
_Static_assert(sizeof(struct d3d9_init_params) == 32, "d3d9_init_params");
""")

    # ---- mirrors -------------------------------------------------------
    o.append("""/* ------------------------------------------------------------------------
 * Mirrors.  The wire form of each of these is the i386 MEMORY IMAGE of the
 * SDK struct; the unix entry expands it into a host one.  The macro follows
 * airconv_thunks.h:164-168: on a 64-bit build assert the mirror, on the
 * 32-bit build assert the mirror AND the SDK struct it is an image of.
 * ------------------------------------------------------------------------ */

#if defined(__LP64__) || defined(_WIN64)
#define D3D9SHIM_COMPATIBLE_STRUCT32(native, mirror, size) \\
    _Static_assert(sizeof(struct mirror) == (size), "incompatible struct size");
#else
#define D3D9SHIM_COMPATIBLE_STRUCT32(native, mirror, size) \\
    _Static_assert(sizeof(struct mirror) == (size), "incompatible struct size"); \\
    _Static_assert(sizeof(native) == (size), "incompatible struct size");
#endif
""")
    for s in api.MIRROR_STRUCTS:
        mirror = "d3d9_%s32" % s["name"]
        o.append("/* %s */" % s["note"].replace("*/", "* /"))
        o.append("struct %s {" % mirror)
        for ctype, name, _o32, _o64, role in s["fields"]:
            o.append("    %-10s %-30s /* %s */" % (ctype, name + ";", role))
        o.append("};")
        o.append("D3D9SHIM_COMPATIBLE_STRUCT32(%s, %s, %d)"
                 % (s["name"], mirror, s["size32"]))
        for ctype, name, off32, _off64, _role in s["fields"]:
            o.append("_Static_assert(offsetof(struct %s, %s) == %d, "
                     '"%s.%s");' % (mirror, name, off32, mirror, name))
        o.append("#if defined(__LP64__) || defined(_WIN64)")
        o.append("_Static_assert(sizeof(%s) == %d, \"%s host layout\");"
                 % (s["name"], s["size64"], s["name"]))
        o.append("#endif")
        o.append("")

    # ---- layout-identical ---------------------------------------------
    o.append("""/* ------------------------------------------------------------------------
 * Layout-identical: same size AND same field offsets under both ABIs, so the
 * unix entry points at the converted guest address in place rather than
 * copying.  If one of these ever stops matching, the assert fires on
 * whichever side changed and the in-place pointer stops being emitted.
 * ------------------------------------------------------------------------ */
""")
    for name, size in api.IDENTICAL_STRUCTS:
        o.append('_Static_assert(sizeof(%s) == %d, "%s is not layout-identical");'
                 % (name, size, name))
    o.append("")
    o.append("""/* Field offsets identical, TAIL PADDING not: a LARGE_INTEGER member gives
 * the struct 8-byte alignment on LP64 and 4 on i386.  So the fields may be
 * read and written at the same offsets, but the struct MAY NOT be pointed at
 * in place across the boundary: a host-typed write to a guest buffer runs
 * sizeof() bytes, which is past the end of the i386 image.
 * D3DADAPTER_IDENTIFIER9 lives on the stack in every title that calls
 * GetAdapterIdentifier, and the frontend opens with
 * memset(p, 0, sizeof(*p)) -- four bytes onto the caller's /GS cookie, which
 * surfaces as a 0xC0000409 fast-fail in the application's own epilogue with
 * no D3D9 frame anywhere near it.  Hence the bounce below. */""")
    for name, size32, size64, offs in api.PADDING_ONLY_STRUCTS:
        o.append("#define D3D9SHIM_SIZE32_%s %d" % (name, size32))
        o.append("#define D3D9SHIM_SIZE64_%s %d" % (name, size64))
        for fname, off in offs:
            o.append('_Static_assert(offsetof(%s, %s) == %d, "%s.%s moved");'
                     % (name, fname, off, name, fname))
        o.append("#if defined(__LP64__) || defined(_WIN64)")
        o.append('_Static_assert(sizeof(%s) == %d, "%s");' % (name, size64, name))
        o.append("#else")
        o.append('_Static_assert(sizeof(%s) == %d, "%s");' % (name, size32, name))
        o.append("#endif")
        o.append('_Static_assert(D3D9SHIM_SIZE32_%s <= D3D9SHIM_SIZE64_%s,'
                 ' "the i386 image of %s must fit in the host struct");'
                 % (name, name, name))
    o.append("")
    o.append("""/* The ONLY way a padding-only struct crosses.  Both directions copy exactly
 * D3D9SHIM_SIZE32_<T> bytes -- the i386 image -- and the assert inside the
 * macro is what makes "never touch a guest buffer with the host sizeof()" a
 * build failure instead of a review item.  The generator refuses to emit an
 * in-place pointer for one of these (generator_self_check), so these two
 * macros are the whole copy surface. */
#define D3D9_COPY32_OUT(T, guest, host_struct)                                \\
    do {                                                                      \\
        _Static_assert(D3D9SHIM_SIZE32_##T <= sizeof(T),                      \\
                       "the i386 image of " #T " must fit in the host struct");\\
        memcpy((void *)(guest), (const void *)(host_struct),                  \\
               (size_t)D3D9SHIM_SIZE32_##T);                                  \\
    } while (0)

#define D3D9_COPY32_IN(T, host_struct, guest)                                 \\
    do {                                                                      \\
        _Static_assert(D3D9SHIM_SIZE32_##T <= sizeof(T),                      \\
                       "the i386 image of " #T " must fit in the host struct");\\
        memcpy((void *)(host_struct), (const void *)(guest),                  \\
               (size_t)D3D9SHIM_SIZE32_##T);                                  \\
    } while (0)
""")

    # ---- parameter blocks ---------------------------------------------
    o.append("""/* ------------------------------------------------------------------------
 * Parameter blocks, one per vtable slot.  Also the ring record payloads for
 * the deferred ops: a ring record is `struct d3d9_ring_record` followed by
 * the block for its opcode, which is why every block size is a multiple of 8.
 * ------------------------------------------------------------------------ */

struct d3d9_ring_record {
    uint16_t op;             /* enum d3d9shim_op */
    uint16_t len;            /* sizeof(record) + sizeof(block), 8-aligned */
    uint32_t seq;            /* monotonic; asserted at replay (8.6) */
};
_Static_assert(sizeof(struct d3d9_ring_record) == 8, "d3d9_ring_record");
""")
    for it, m in api.iter_methods():
        name = api.block_struct(it, m)
        o.append("/* %s::%s -- slot %d, %s%s */"
                 % (it["iface"], m["name"], m["slot"], m["disp"],
                    ", flushes" if m["flush"] else ""))
        o.append("struct %s {" % name)
        for ctype, fname, role in api.block_fields(m):
            note = {"self": "receiving object's native handle",
                    "ret": "result"}.get(role, "")
            if role == "arg":
                a = next(x for x in m["args"] if x["name"] == fname)
                note = a["shape"]
            o.append("    %-10s %-30s /* %s */" % (ctype, fname + ";", note))
        for i in range(api.pad_words(m)):
            o.append("    uint32_t   _pad%d;" % i)
        o.append("};")
        o.append('_Static_assert(sizeof(struct %s) == %d, "%s");'
                 % (name, api.block_size(m), name))
        off = 0
        for ctype, fname, _role in api.block_fields(m):
            width = 8 if ctype == "uint64_t" else 4
            off = (off + width - 1) // width * width
            o.append('_Static_assert(offsetof(struct %s, %s) == %d, "%s.%s");'
                     % (name, fname, off, name, fname))
            off += width
        o.append("")

    # ---- transport blocks ----------------------------------------------
    o.append("""/* ------------------------------------------------------------------------
 * Transport blocks.  Same fixed-width rule as a vtable block -- uint64_t
 * fields first, then the 4-byte ones, then the result, then padding to a
 * multiple of 8 -- so one definition is right on i386 and on LP64 here too.
 *
 * These three were hand-written in d3d9shim_object.h and sat PAST the end of
 * a table sized D3D9SHIM_OP_COUNT, so neither dispatch table had an entry for
 * them and every call on one failed the bind.  d3d9_api.py now describes
 * them, which is what gets them entries; the layouts below are the ones the
 * hand-written header _Static_asserted, unchanged.
 * ------------------------------------------------------------------------ */
""")
    for name, value in api.WINDOW_STATE_FLAGS:
        o.append("#define %-30s 0x%xu" % (name, value))
    o.append("")
    o.append("""/* The distinguished status a unix entry returns when THIS call could not be
 * served because the guest arena is empty or full.  d3d9shim_native_call()
 * answers it by growing the arena and retrying the same block exactly once
 * (8.2(c): grow-and-retry, no upcall machinery).  It is emitted here rather
 * than declared once per side so the two halves cannot disagree about the
 * value; the entry only raises it on a call that already FAILED, so the retry
 * can never double work that succeeded. */
#ifndef D3D9SHIM_STATUS_ARENA_EXHAUSTED
#define D3D9SHIM_STATUS_ARENA_EXHAUSTED  0xC0000017u  /* STATUS_NO_MEMORY */
#endif
""")
    for i, t in enumerate(api.TRANSPORT_SLOTS):
        o.append("/* slot %d -- %s */" % (TRANSPORT_BASE + i,
                                          t["note"].replace("*/", "* /")))
        o.append("struct %s {" % t["block"])
        roles = {f[1]: f[2] for f in t["fields"]}
        for ctype, fname, role in api.transport_fields(t):
            note = "OUT: result" if role == "ret" else roles[fname]
            o.append("    %-10s %-30s /* %s */" % (ctype, fname + ";", note))
        for j in range(api.transport_pad_words(t)):
            o.append("    uint32_t   _pad%d;" % j)
        o.append("};")
        o.append('_Static_assert(sizeof(struct %s) == %d, "%s");'
                 % (t["block"], t["size"], t["block"]))
        off = 0
        for ctype, fname, _role in api.transport_fields(t):
            width = 8 if ctype == "uint64_t" else 4
            off = (off + width - 1) // width * width
            o.append('_Static_assert(offsetof(struct %s, %s) == %d, "%s.%s");'
                     % (t["block"], fname, off, t["block"], fname))
            off += width
        o.append("")

    o.append("#endif /* __MADEIRA_D3D9SHIM_OPS_H */")
    return "\n".join(o) + "\n"


