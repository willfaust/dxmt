# --------------------------------------------------------------------------
# Small helpers over the description
# --------------------------------------------------------------------------

AMBIGUOUS_IFACES = ("IDirect3DBaseTexture9", "IDirect3DResource9", "IUnknown")


def iface_kinds():
    """Every interface name that can appear in an iface_in/iface_out tag."""
    out = {}
    for it in api.INTERFACES:
        out[it["iface"]] = it["kind"]
        if it["iface"].endswith("Ex"):
            out[it["iface"][:-2]] = it["kind"]
    for name in AMBIGUOUS_IFACES:
        out[name] = "ANY"
    return out


KINDS = iface_kinds()


def kind_enum(kind):
    return "D3D9SHIM_KIND_" + kind


def state_struct(kind):
    return "d3d9shim_" + kind.lower()


def opcodes():
    """[(name, it, m)] in canonical order; index IS the unix table slot.

    Slot 0 is the init handshake, 1..320 the vtable methods, and then the
    three TRANSPORT slots -- the things the boundary needs that are not
    vtable methods.  They come last so no generated slot number moves, which
    is how they keep the numbers (321, 322, 323) the hand-written half already
    ships against; a transport entry is (name, None, <TRANSPORT_SLOTS dict>).
    """
    out = [("D3D9OP_init", None, None)]
    for it, m in api.iter_methods():
        out.append((api.opcode_name(it, m), it, m))
    for t in api.TRANSPORT_SLOTS:
        out.append((t["op"], None, t))
    return out


OPS = opcodes()
TRANSPORT_BASE = 1 + api.EXPECTED_TOTAL_SLOTS


def is_transport(it, m):
    return it is None and m is not None


def op_symbol(it, m):
    """The _d3d9_<sym> / d3d9_call_<sym> stem for one table slot."""
    if m is None:
        return "init"
    if it is None:
        return m["name"]
    return api.symbol(it, m)


def transport_params(t):
    """The transport hook's C parameter list, from the field roles."""
    ps = []
    for ctype, name, role in t["fields"]:
        base = role.split(":", 1)[0]
        if base == "scalar":
            ps.append("%s %s" % (role.split(":", 1)[1], name))
        elif base == "hwnd32":
            ps.append("HWND " + name)
        elif base == "guest_ptr":
            ps.append("void *" + name)
        elif base == "handle_out":
            ps.append("d3d9_native_handle *" + name)
        else:
            raise SystemExit("unknown transport role %r" % role)
        del ctype
    return ", ".join(ps)


def mirror_of(shape):
    t = shape.split(":", 1)[-1]
    for s in api.MIRROR_STRUCTS:
        if s["name"] == t:
            return s
    return None


MIRROR_BY_NAME = {s["name"]: s for s in api.MIRROR_STRUCTS}
PADDING_ONLY = {p[0] for p in api.PADDING_ONLY_STRUCTS}
IDENTICAL_BY_NAME = {s[0]: s[1] for s in api.IDENTICAL_STRUCTS}
LOCKED = {"locked_rect_out": "D3DLOCKED_RECT", "locked_box_out": "D3DLOCKED_BOX"}


def arg_target(a):
    """The pointed-at type for a shaped pointer argument."""
    if a["tag"] in LOCKED:
        return LOCKED[a["tag"]]
    if a["tag"] in ("in_struct", "out_struct", "inout_struct", "out_ptr"):
        return a["shape"].split(":", 1)[1]
    if a["tag"] in ("in_array", "out_array"):
        return a["shape"].split(":")[1]
    return None


def guest_ptr_target(a):
    """`void **ppbData` -> `void *`: the type the OUT pointer points at."""
    base = a["ctype"].strip()
    assert base.endswith("**"), a["ctype"]
    return base[:-2].strip() + " *"


def is_iface_array(a):
    """An in_array whose elements are guest interface pointers."""
    return a["tag"] == "in_array" and a["shape"].split(":")[1] in KINDS


def count_expr(a):
    if a["tag"] in ("in_array", "out_array"):
        return a["shape"].split(":", 2)[2]
    if a["tag"] == "user_mem_in":
        return a["shape"].split(":", 1)[1]
    return None


def shim_params(it, m):
    """The shim thunk's C parameter list, matching the SDK vtable exactly."""
    ps = ["%s *iface" % it["iface"]]
    for a in m["args"]:
        ctype = a["ctype"]
        ps.append(("%s %s" if ctype.endswith(("*", "&")) else "%s %s")
                  % (ctype, a["name"]))
    return ", ".join(ps)


def native_ret(m):
    return "void" if m["ret"] == "void" else m["ret"]


def native_params(it, m):
    """The native hook's C parameter list: host types, handles for objects."""
    ps = ["d3d9_native_handle self"]
    for a in m["args"]:
        t, n = a["tag"], a["name"]
        if t == "iface_in":
            ps.append("d3d9_native_handle " + n)
        elif t == "iface_out":
            ps.append("d3d9_native_handle *" + n)
        elif t in ("handle", "hwnd"):
            ps.append("%s %s" % ("HWND" if t == "hwnd" else "HANDLE", n))
        elif t == "shared_handle_inout":
            ps.append("HANDLE *" + n)
        elif t == "user_mem_in":
            ps.append("const void *" + n)
        elif t in LOCKED:
            ps.append("%s *%s" % (LOCKED[t], n))
        elif t == "guest_ptr_out":
            # The mapped-memory OUT pointer.  A HOST pointer here: the unix
            # entry is what turns it back into a guest address, exactly as it
            # does for D3DLOCKED_RECT::pBits.
            ps.append("%s*%s" % (guest_ptr_target(a), n))
        elif t == "in_array" and is_iface_array(a):
            ps.append("const uint32_t *" + n)   # guest interface pointers
        elif t in ("in_struct", "in_array"):
            ps.append("const %s *%s" % (arg_target(a), n))
        elif t in ("out_struct", "inout_struct", "out_array", "out_ptr"):
            ps.append("%s *%s" % (arg_target(a), n))
        else:
            ps.append("%s %s" % (a["ctype"], n))
    return ", ".join(ps)


# --------------------------------------------------------------------------
# Predicate / count-expression translation.  The grammar d3d9_api.validate()
# enforces is small on purpose, so this is a token rewrite, not a parser.
# --------------------------------------------------------------------------

import re                                                    # noqa: E402

_CALL_REWRITE = [
    (r"\bis_null\s*\(([^()]*)\)", r"((\1) == NULL)"),
    (r"\bsame_device\s*\(([^()]*)\)",
     r"d3d9shim_same_device(&_self->hdr, (struct d3d9shim_object *)(\1))"),
    (r"\bhas_usage\s*\(([^()]*),([^()]*)\)",
     r"d3d9shim_has_usage((struct d3d9shim_object *)(\1), (\2))"),
]


def to_c(expr):
    """Python-syntax predicate / count expression -> C."""
    out = expr
    for pat, rep in _CALL_REWRITE:
        prev = None
        while prev != out:
            prev, out = out, re.sub(pat, rep, out)
    out = re.sub(r"\bself\.(\w+)", r"_self->\1", out)
    out = re.sub(r"\bUINT_MAX\b", "0xffffffffu", out)
    out = re.sub(r"\bTrue\b", "1", out)
    out = re.sub(r"\bFalse\b", "0", out)
    out = re.sub(r"\bnot\b", "!", out)
    out = re.sub(r"\band\b", "&&", out)
    out = re.sub(r"\bor\b", "||", out)
    return out


POINTER_TAGS = ("in_struct", "out_struct", "inout_struct", "in_array",
                "out_array", "out_ptr", "user_mem_in", "locked_rect_out",
                "locked_box_out", "shared_handle_inout", "guest_ptr_out")


def to_c_size(expr, m):
    """A count/size expression, evaluated in a unix entry.

    An argument that is a POINTER becomes the entry's converted host pointer
    (`_name`); a scalar becomes the parameter-block field (`_p->name`).  A
    leading `*name` with no space means "the count is read through that
    out_ptr argument" -- D3D9's query-size-then-fill idiom -- and becomes
    D3D9_DEREF32(), which the glue defines to be NULL- and window-safe so the
    read is valid even though that argument's own validation has not run yet.
    Multiplication must be written with spaces (`count * 4`), which is what
    keeps `*x` unambiguous.
    """
    ptr = {a["name"] for a in m["args"] if a["tag"] in POINTER_TAGS}

    out = re.sub(r"\*(\w+)", "\x01" + r"\1" + "\x02", expr)

    def name(mo):
        n = mo.group(1)
        return ("_" + n) if n in ptr else ("_p->" + n)

    # \b after \w* stops the engine backtracking into the middle of an
    # identifier to satisfy the "not a call" lookahead, which would turn
    # d3d9_up_vertex_bytes(...) into _p->d3d9_up_vertex_byte + "s(...)".
    out = re.sub(r"(?<![\w.\x01])([A-Za-z_]\w*)\b(?!\s*\()", name, out)
    out = re.sub("\x01(\\w+)\x02",
                 lambda mo: "D3D9_DEREF32(%s)"
                 % (("_" + mo.group(1)) if mo.group(1) in ptr
                    else ("_p->" + mo.group(1))), out)
    return out


