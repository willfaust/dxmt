def unix_bail(it, m, n, indent):
    """The "this guest pointer is not usable" arm of a unix entry.

    A converted pointer that is not inside the window is D3DERR_INVALIDCALL,
    never a host dereference: after the frontend moves natively a bad app
    pointer faults in HOST code rather than as a guest c0000005 the app's SEH
    could catch (8.9-4), so the entry has to be the one that says no.
    """
    pad = " " * indent
    out = [pad + 'D3D9_LOG("%s::%s: %s is not a usable guest pointer");'
           % (it["iface"], m["name"], n)]
    if m["ret"] != "void":
        out.append(pad + "_p->ret = D3DERR_INVALIDCALL;")
    out.append(pad + "return;")
    return out


def unix_convert(it, m):
    """Locals + conversions for one unix entry.  Returns (decls, pre, post,
    callargs)."""
    decls, pre, post, callargs = [], [], [], ["_p->self"]
    pool = "_p->pool" if any(a["name"] == "pool" for a in m["args"]) \
        else "D3D9_NO_POOL"
    for a in m["args"]:
        n, t = a["name"], a["tag"]
        if t == "iface_in":
            callargs.append("_p->%s" % n)
        elif t == "iface_out":
            decls.append("    d3d9_native_handle _%s = 0;" % n)
            callargs.append("&_%s" % n)
            post.append("    _p->%s = _%s;" % (n, n))
        elif t == "hwnd":
            callargs.append("(HWND)(ULONG_PTR)_p->%s" % n)
        elif t == "handle":
            callargs.append("(HANDLE)(ULONG_PTR)_p->%s" % n)
        elif t == "u64":
            callargs.append("_p->%s" % n)
        elif t == "u32":
            callargs.append("(%s)_p->%s" % (a["ctype"].strip(), n))
        elif t == "shared_handle_inout":
            decls.append("    ULONG *_%s_g = D3D9_HOST_PTR(_p->%s);" % (n, n))
            decls.append("    HANDLE _%s = NULL;" % n)
            pre.append("    if (_%s_g) {" % n)
            pre.append("        if (!D3D9_IN_WINDOW(_%s_g, sizeof(ULONG))) {" % n)
            pre += unix_bail(it, m, n, 12)
            pre.append("        }")
            pre.append("        _%s = D3D9_SHARED_IN(_%s_g, %s);" % (n, n, pool))
            pre.append("    }")
            callargs.append("_%s_g ? &_%s : NULL" % (n, n))
            post.append("    if (_%s_g)" % n)
            post.append("        D3D9_SHARED_OUT(_%s_g, _%s, %s);" % (n, n, pool))
        elif t == "guest_ptr_out":
            # The mapped-memory OUT pointer.  Nothing comes IN -- the shim
            # packs nothing and refuses a NULL out-parameter itself -- so the
            # entry hands the hook a host slot and converts the answer back
            # with ios_wow_guest_ptr32(), which is the same rule as
            # D3DLOCKED_RECT::pBits and the same guarantee: the pointer the
            # native allocator hands out is always inside the guest arena.
            decls.append("    %s_%s = NULL;" % (guest_ptr_target(a), n))
            callargs.append("&_%s" % n)
            post.append("    _p->%s = %s ? D3D9_GUEST_PTR32(_%s) : 0;"
                        % (n, "SUCCEEDED(_p->ret)" if m["ret"] == "HRESULT"
                           else "1", n))
        elif t in LOCKED:
            host = LOCKED[t]
            mirror = "d3d9_%s32" % host
            decls.append("    %s _%s;" % (host, n))
            decls.append("    struct %s *_%s_g = D3D9_HOST_PTR(_p->%s);"
                         % (mirror, n, n))
            pre.append("    memset(&_%s, 0, sizeof(_%s));" % (n, n))
            pre.append("    if (_%s_g && !D3D9_IN_WINDOW(_%s_g, sizeof(*_%s_g))) {"
                       % (n, n, n))
            pre += unix_bail(it, m, n, 8)
            pre.append("    }")
            callargs.append("_%s_g ? &_%s : NULL" % (n, n))
            post.append("    if (_%s_g && SUCCEEDED(_p->ret))" % n)
            post.append("        d3d9_mirror_out_%s(_%s_g, &_%s);" % (host, n, n))
        elif t in ("in_struct", "out_struct", "inout_struct") \
                and arg_target(a) in MIRROR_BY_NAME:
            host = arg_target(a)
            mirror = "d3d9_%s32" % host
            decls.append("    %s _%s;" % (host, n))
            decls.append("    struct %s *_%s_g = D3D9_HOST_PTR(_p->%s);"
                         % (mirror, n, n))
            pre.append("    memset(&_%s, 0, sizeof(_%s));" % (n, n))
            pre.append("    if (_%s_g) {" % n)
            pre.append("        if (!D3D9_IN_WINDOW(_%s_g, sizeof(*_%s_g))) {"
                       % (n, n))
            pre += unix_bail(it, m, n, 12)
            pre.append("        }")
            if t in ("in_struct", "inout_struct"):
                pre.append("        d3d9_mirror_in_%s(&_%s, _%s_g);" % (host, n, n))
            pre.append("    }")
            callargs.append("_%s_g ? &_%s : NULL" % (n, n))
            if t in ("out_struct", "inout_struct"):
                post.append("    if (_%s_g)" % n)
                post.append("        d3d9_mirror_out_%s(_%s_g, &_%s);"
                            % (host, n, n))
        elif t in ("in_struct", "out_struct", "inout_struct") \
                and arg_target(a) in PADDING_ONLY:
            # A PADDING-ONLY struct: every field is at the same offset, but the
            # host sizeof() is LARGER than the i386 image (D3DADAPTER_IDENTIFIER9
            # is 1104 / 1100).  It used to be pointed at in place, which handed
            # the frontend a host-typed pointer into a guest buffer that is
            # short by the tail padding -- and MTLD3D9Interface::
            # GetAdapterIdentifier opens with memset(p, 0, sizeof(*p)), so the
            # application's D3DADAPTER_IDENTIFIER9 (a stack local in every title
            # that calls it) lost four bytes past its end: the /GS cookie, i.e.
            # a 0xC0000409 fast-fail in the caller's epilogue with no D3D9 call
            # anywhere near the faulting address.
            #
            # So it BOUNCES, exactly like a mirror: the frontend writes a host
            # struct and D3D9_COPY32_OUT copies back D3D9SHIM_SIZE32_<T> bytes
            # and not one more.  That macro is the only copy path for these and
            # carries its own _Static_assert (d3d9shim_ops.h).
            host = arg_target(a)
            decls.append("    %s _%s;" % (host, n))
            decls.append("    void *_%s_g = D3D9_HOST_PTR(_p->%s);" % (n, n))
            pre.append("    memset(&_%s, 0, sizeof(_%s));" % (n, n))
            pre.append("    if (_%s_g) {" % n)
            pre.append("        if (!D3D9_IN_WINDOW(_%s_g, D3D9SHIM_SIZE32_%s)) {"
                       % (n, host))
            pre += unix_bail(it, m, n, 12)
            pre.append("        }")
            if t in ("in_struct", "inout_struct"):
                pre.append("        D3D9_COPY32_IN(%s, &_%s, _%s_g);"
                           % (host, n, n))
            pre.append("    }")
            callargs.append("_%s_g ? &_%s : NULL" % (n, n))
            if t in ("out_struct", "inout_struct"):
                post.append("    if (_%s_g)" % n)
                post.append("        D3D9_COPY32_OUT(%s, _%s_g, &_%s);"
                            % (host, n, n))
        else:
            # layout-identical: point at the converted guest address in place
            target = arg_target(a) or "void"
            elem = target
            const = "const " if t in ("in_struct", "in_array", "user_mem_in") \
                else ""
            if t == "user_mem_in":
                base = "void"
            elif is_iface_array(a):
                # an array of GUEST interface pointers: 4 bytes each, and the
                # per-element handle translation is the glue's job (this is
                # the API's only 2-level IN array).
                base = elem = "uint32_t"
            else:
                base = target
            cast = "%s%s *" % (const, base)
            decls.append("    %s_%s = D3D9_HOST_PTR(_p->%s);" % (cast, n, n))
            size = count_expr(a)
            if size is None:
                # A padding-only struct is LARGER on the host than in the
                # guest, so its window check must use the i386 size or a
                # buffer at the very end of a mapping is falsely rejected --
                # and the native hook must not write past it either.
                size = ("D3D9SHIM_SIZE32_%s" % target) if target in PADDING_ONLY \
                    else "sizeof(%s)" % target
            elif t == "user_mem_in":
                size = "(size_t)(%s)" % to_c_size(size, m)
            else:
                size = "(size_t)(%s) * sizeof(%s)" % (to_c_size(size, m), elem)
            pre.append("    if (_%s && !D3D9_IN_WINDOW(_%s, %s)) {" % (n, n, size))
            pre += unix_bail(it, m, n, 8)
            pre.append("    }")
            callargs.append("_%s" % n)
    return decls, pre, post, callargs


def emit_unix_c():
    o = [BANNER % "d3d9_unix.c -- one unix entry per D3D9 vtable slot"]
    o.append("""#include <string.h>

#include "d3d9shim_ops.h"
#include "d3d9_native_hooks.h"

/* The hand-written glue (d3d9_native_glue.cpp + d3d9_unix_glue.h) must
 * define, before this file is compiled:
 *
 *   NTSTATUS, STATUS_SUCCESS, STATUS_REVISION_MISMATCH, STATUS_NOT_SUPPORTED,
 *   STATUS_INVALID_PARAMETER, STATUS_NOT_IMPLEMENTED
 *   D3D9_HOST_PTR(u32)        -> void *, NULL-preserving; ios_wow_host_ptr()
 *   D3D9_GUEST_PTR32(void *)  -> ULONG;  ios_wow_guest_ptr32()
 *   D3D9_IN_WINDOW(p, bytes)  -> int; false for anything outside [B, B+4G)
 *   D3D9_DEREF32(p)           -> the ULONG at a validated guest address
 *   D3D9_SHARED_IN(slot, pool) / D3D9_SHARED_OUT(slot, h, pool)
 *   D3D9_NO_POOL, D3D9_LOG(msg)
 *   D3D9_ARENA_TAKE_STARVED()  -> non-zero if an app-visible allocation on
 *                                 THIS thread could not be served since the
 *                                 last call; reading it clears it.
 *
 * EVERY embedded pointer is converted before any dereference and NULL stays
 * NULL (7.4 rule 1); every converted pointer is range-checked before it is
 * handed to the frontend, so a bad guest pointer is D3DERR_INVALIDCALL and
 * not a host fault the application's SEH can never see (8.9-4). */

#include "d3d9_unix_glue.h"

/* Variable-length input scanners, named by the count expressions in
 * d3d9_api.py.  The glue implements them; each walks GUEST memory, so each
 * must window-check as it walks and return 0 for anything it cannot follow.
 * D3D9_IN_WINDOW(p, 0) still validates the base address, so a 0 from one of
 * these does not weaken the check that follows it. */
extern size_t d3d9_decl_element_count(const D3DVERTEXELEMENT9 *elements);
extern size_t d3d9_shader_token_count(const DWORD *byte_code);
extern size_t d3d9_up_vertex_bytes(D3DPRIMITIVETYPE type, UINT primitive_count,
                                   UINT stride);
extern size_t d3d9_up_index_bytes(D3DPRIMITIVETYPE type, UINT primitive_count,
                                  D3DFORMAT index_format);
""")
    # mirror conversions
    o.append("/* ---- mirror conversions "
             "-------------------------------------------- */\n")
    used_in, used_out = set(), set()
    for it, m in api.iter_methods():
        for a in m["args"]:
            target = LOCKED.get(a["tag"]) or arg_target(a)
            if target not in MIRROR_BY_NAME:
                continue
            if a["tag"] in ("in_struct", "inout_struct"):
                used_in.add(target)
            if a["tag"] in LOCKED or a["tag"] in ("out_struct", "inout_struct"):
                used_out.add(target)
    for s in api.MIRROR_STRUCTS:
        host, mirror = s["name"], "d3d9_%s32" % s["name"]
        assert host in used_out, host
        if host not in used_in:
            o.append("/* %s never crosses INWARD, so it has no "
                     "d3d9_mirror_in_%s(). */" % (host, host))
            o.append("")
        if host in used_in:
            o.append("static void d3d9_mirror_in_%s(%s *dst, const struct %s *src)"
                     % (host, host, mirror))
            o.append("{")
            o.append("    memset(dst, 0, sizeof(*dst));")
            done = set()
            for ctype, name, _o32, _o64, role in s["fields"]:
                if role == "scalar":
                    o.append("    dst->%s = src->%s;" % (name, name))
                elif role == "hwnd":
                    o.append("    dst->%s = (HWND)(ULONG_PTR)src->%s;"
                             % (name, name))
                elif role == "guest_ptr":
                    o.append("    dst->%s = D3D9_HOST_PTR(src->%s);"
                             % (name, name))
                elif role == "u64_lo":
                    base = name[:-3]
                    if base in done:
                        continue
                    done.add(base)
                    o.append("    dst->%s.LowPart = src->%s_lo;" % (base, base))
                    o.append("    dst->%s.HighPart = (LONG)src->%s_hi;"
                             % (base, base))
            o.append("}\n")
        o.append("static void d3d9_mirror_out_%s(struct %s *dst, const %s *src)"
                 % (host, mirror, host))
        o.append("{")
        done = set()
        for ctype, name, _o32, _o64, role in s["fields"]:
            if role == "scalar":
                o.append("    dst->%s = src->%s;" % (name, name))
            elif role == "hwnd":
                o.append("    dst->%s = (uint32_t)(ULONG_PTR)src->%s;"
                         % (name, name))
            elif role == "guest_ptr":
                o.append("    dst->%s = D3D9_GUEST_PTR32(src->%s);" % (name, name))
            elif role == "u64_lo":
                base = name[:-3]
                if base in done:
                    continue
                done.add(base)
                o.append("    dst->%s_lo = src->%s.LowPart;" % (base, base))
                o.append("    dst->%s_hi = (uint32_t)src->%s.HighPart;"
                         % (base, base))
        o.append("}\n")

    # init
    o.append("""/* ---- the init handshake ------------------------------------------------ */

NTSTATUS _d3d9_init(void *args)
{
    struct d3d9_init_params *_p = args;

    _p->native_hash = D3D9SHIM_API_HASH;
    if (_p->api_hash != D3D9SHIM_API_HASH || _p->api_version != D3D9SHIM_API_VERSION
        || _p->op_count != D3D9SHIM_OP_COUNT) {
        D3D9_LOG("d3d9: shim/native API description mismatch; refusing");
        _p->status = D3D9SHIM_INIT_HASH_MISMATCH;
        return STATUS_REVISION_MISMATCH;
    }
    /* This wire format cannot express a 64-bit pointer, so a 64-bit caller
     * has no correct reading of a parameter block.  Fail loudly rather than
     * zero-extend something (7.4 rule 4). */
    if (_p->ptr_size != 4) {
        D3D9_LOG("d3d9: the shim ABI is 32-bit only");
        _p->status = D3D9SHIM_INIT_BAD_PTR_SIZE;
        return STATUS_NOT_SUPPORTED;
    }
    if (!d3d9_native_init()) {
        _p->status = D3D9SHIM_INIT_NATIVE_FAILED;
        return STATUS_UNSUCCESSFUL;
    }
    _p->status = D3D9SHIM_INIT_OK;
    return STATUS_SUCCESS;
}

/* ---- one entry per slot ------------------------------------------------ */
""")

    for it, m in api.iter_methods():
        sym = api.symbol(it, m)
        block = api.block_struct(it, m)
        o.append("/* %s::%s -- slot %d, %s */"
                 % (it["iface"], m["name"], m["slot"], m["disp"]))
        if m["disp"] == "resolve":
            # A real entry, and the reason `resolve` exists as a disposition:
            # the shim answers this method from its identity cache, but a
            # child native handle is produced by NOTHING ELSE, so the one
            # crossing that fills the cache lands here.
            o.append("/* Answers the identity cache in the shim on a miss; "
                     "the handle it\n * writes into the block is what the "
                     "guest wrapper is built from. */")
        if m["disp"] == "local":
            o.append("NTSTATUS _d3d9_%s(void *args)" % sym)
            o.append("{")
            o.append("    /* answered in the shim (%s); reaching the unix side "
                     "means the\n     * two halves disagree about the "
                     "description. */" % m["local"])
            o.append("    (void)args;")
            o.append('    D3D9_LOG("d3d9: %s::%s crossed but is local");'
                     % (it["iface"], m["name"]))
            o.append("    return STATUS_NOT_IMPLEMENTED;")
            o.append("}")
            o.append("")
            continue

        decls, pre, post, callargs = unix_convert(it, m)
        o.append("static void d3d9_call_%s(struct %s *_p)" % (sym, block))
        o.append("{")
        for d in decls:
            o.append(d)
        if decls:
            o.append("")
        for p in pre:
            o.append(p)
        call = "d3d9_native_%s(%s);" % (sym, ", ".join(callargs))
        if m["ret"] == "void":
            o.append("    " + call)
        else:
            o.append("    _p->ret = d3d9_native_%s(%s);"
                     % (sym, ", ".join(callargs))
                     if m["ret"] != "HMONITOR" else
                     "    _p->ret = (uint64_t)(ULONG_PTR)d3d9_native_%s(%s);"
                     % (sym, ", ".join(callargs)))
        for p in post:
            o.append(p)
        o.append("}")
        o.append("")
        o.append("NTSTATUS _d3d9_%s(void *args)" % sym)
        o.append("{")
        if m["ret"] == "HRESULT":
            # An app-visible allocation that could not be served leaves a
            # per-thread mark.  If it also made THIS call fail, say so with
            # the distinguished status instead of an opaque E_OUTOFMEMORY:
            # the shim grows the arena and retries the same block once
            # (8.2(c)).  The mark is taken unconditionally so it cannot leak
            # into the next call, and acted on only on a failed HRESULT, so a
            # retry can never repeat work that succeeded.
            o.append("    struct d3d9_%s_params *_p = args;" % sym)
            o.append("    int _starved;")
            o.append("")
            o.append("    d3d9_call_%s(_p);" % sym)
            o.append("    _starved = D3D9_ARENA_TAKE_STARVED();")
            o.append("    if (_starved && FAILED((HRESULT)_p->ret))")
            o.append("        return (NTSTATUS)D3D9SHIM_STATUS_ARENA_EXHAUSTED;")
            o.append("    return STATUS_SUCCESS;")
        else:
            o.append("    d3d9_call_%s(args);" % sym)
            o.append("    return STATUS_SUCCESS;")
        o.append("}")
        o.append("")

    # ---- the transport slots --------------------------------------------
    o.append("""/* ---- the transport slots -----------------------------------------------
 * Not vtable methods, so nothing in the interface description produces them;
 * see TRANSPORT_SLOTS in d3d9_api.py.  They keep the numbers the hand-written
 * shim half already calls with, immediately after the generated range. */
""")
    for i, t in enumerate(api.TRANSPORT_SLOTS):
        o.append("/* %s -- slot %d, transport */" % (t["name"], TRANSPORT_BASE + i))
        o.append("static void d3d9_call_%s(struct %s *_p)" % (t["name"], t["block"]))
        o.append("{")
        decls, pre, callargs = [], [], []
        for ctype, fname, role in t["fields"]:
            base = role.split(":", 1)[0]
            if base == "scalar":
                callargs.append("(%s)_p->%s" % (role.split(":", 1)[1], fname))
            elif base == "hwnd32":
                callargs.append("(HWND)(ULONG_PTR)_p->%s" % fname)
            elif base == "guest_ptr":
                size = role.split(":", 1)[1]
                size = size if size.isdigit() else "_p->" + size
                decls.append("    void *_%s = D3D9_HOST_PTR(_p->%s);" % (fname, fname))
                pre.append("    if (!_%s || !D3D9_IN_WINDOW(_%s, %s)) {"
                           % (fname, fname, size))
                pre.append('        D3D9_LOG("d3d9: %s: %s is not a usable '
                           'guest pointer");' % (t["name"], fname))
                pre.append("        _p->ret = D3DERR_INVALIDCALL;")
                pre.append("        return;")
                pre.append("    }")
                callargs.append("_%s" % fname)
            elif base == "handle_out":
                decls.append("    d3d9_native_handle _%s = 0;" % fname)
                callargs.append("&_%s" % fname)
            del ctype
        for d in decls:
            o.append(d)
        if decls:
            o.append("")
        o += pre
        if t["ret_zero_ok"]:
            o.append("    _p->ret = %s(%s) ? E_FAIL : D3D_OK;"
                     % (t["hook"], ", ".join(callargs)))
        else:
            o.append("    _p->ret = %s(%s);" % (t["hook"], ", ".join(callargs)))
        for _ctype, fname, role in t["fields"]:
            if role.split(":", 1)[0] == "handle_out":
                o.append("    _p->%s = _%s;" % (fname, fname))
        o.append("}")
        o.append("")
        o.append("NTSTATUS _d3d9_%s(void *args)" % t["name"])
        o.append("{")
        o.append("    d3d9_call_%s(args);" % t["name"])
        o.append("    return STATUS_SUCCESS;")
        o.append("}")
        o.append("")

    # ---- ring replay ----------------------------------------------------
    o.append("""/* ---- ring replay -------------------------------------------------------
 * The ring is a TRANSPORT, not a re-implementation: replay calls exactly the
 * same d3d9_call_* the synchronous entry does (8.6).  `seq` is monotonic and
 * asserted here, which is what turns a ring bug into a refused batch rather
 * than a wrong frame. */

NTSTATUS d3d9_ring_replay(void *base, uint32_t bytes, uint32_t *seq_io)
{
    unsigned char *_p = base, *_end = _p + bytes;

    if (((uintptr_t)base & 7u) || (bytes & 7u))
        return STATUS_INVALID_PARAMETER;
    while (_p + sizeof(struct d3d9_ring_record) <= _end) {
        struct d3d9_ring_record *_r = (struct d3d9_ring_record *)_p;
        void *_blk = _r + 1;

        if (_r->len < sizeof(struct d3d9_ring_record) || (_r->len & 7u)
            || _p + _r->len > _end)
            return STATUS_INVALID_PARAMETER;
        if (_r->seq != *seq_io)
            return STATUS_INVALID_PARAMETER;
        ++*seq_io;
        switch (_r->op) {""")
    for it, m in api.iter_methods():
        if m["disp"] != "defer":
            continue
        sym = api.symbol(it, m)
        block = api.block_struct(it, m)
        o.append("        case %s:" % api.opcode_name(it, m))
        o.append("            if (_r->len != sizeof(struct d3d9_ring_record)"
                 " + sizeof(struct %s))" % block)
        o.append("                return STATUS_INVALID_PARAMETER;")
        o.append("            d3d9_call_%s(_blk);" % sym)
        o.append("            break;")
    o.append("""        default:
            D3D9_LOG("d3d9: ring record with a non-deferrable opcode");
            return STATUS_INVALID_PARAMETER;
        }
        _p += _r->len;
    }
    return _p == _end ? STATUS_SUCCESS : STATUS_INVALID_PARAMETER;
}
""")

    o.append("/* The two dispatch tables are in d3d9_unix_table.c, which "
             "declares every\n * _d3d9_* above itself -- also generated, so "
             "the two cannot drift. */")
    return "\n".join(o) + "\n"


