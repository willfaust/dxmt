def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="diff against what is on disk; exit 1 if it differs")
    ap.add_argument("-o", "--root", default=None,
                    help="repository root (default: inferred from this file)")
    args = ap.parse_args()

    root = args.root or os.path.normpath(
        os.path.join(os.path.dirname(os.path.abspath(__file__)),
                     "..", "..", "..", ".."))

    problems = api.validate() + generator_self_check()
    if problems:
        sys.stderr.write("gen_d3d9_thunks.py: REFUSING to emit, %d problem(s):\n"
                         % len(problems))
        for p in problems:
            sys.stderr.write("  " + p + "\n")
        return 1

    rendered = [(rel, fn()) for rel, fn in OUTPUTS]

    if args.check:
        differs = 0
        for rel, text in rendered:
            path = os.path.join(root, rel)
            try:
                on_disk = open(path, encoding="utf-8", newline="").read()
            except OSError:
                on_disk = None
            if on_disk != text:
                sys.stderr.write("STALE: %s\n" % rel)
                differs += 1
        if differs:
            sys.stderr.write("run gen_d3d9_thunks.py to regenerate\n")
            return 1
        print("up to date (%d files), D3D9SHIM_API_HASH = 0x%016x"
              % (len(rendered), api.api_hash()))
        return 0

    for rel, text in rendered:
        path = os.path.join(root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("%-52s %7d bytes  %5d lines"
              % (rel, len(text), text.count("\n")))
    print("D3D9SHIM_API_HASH = 0x%016x" % api.api_hash())
    return 0


if __name__ == "__main__":
    sys.exit(main())
