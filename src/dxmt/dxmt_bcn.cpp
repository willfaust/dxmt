namespace {
struct BitReader {
  const uint8_t *b; uint32_t pos;
  explicit BitReader(const uint8_t *p) : b(p), pos(0) {}
  uint32_t get(uint32_t n) {
    uint32_t v = 0;
    for (uint32_t i = 0; i < n; i++) {
      v |= (uint32_t)((b[pos >> 3] >> (pos & 7)) & 1) << i;
      pos++;
    }
    return v;
  }
};
inline uint8_t expand(uint32_t v, uint32_t bits) {
  /* replicate high bits into the low ones, per the spec's unquantise */
  return (uint8_t)((v << (8 - bits)) | (v >> (2 * bits - 8)));
}
inline uint8_t interp(uint8_t e0, uint8_t e1, uint16_t w) {
  return (uint8_t)(((64 - w) * (uint32_t)e0 + w * (uint32_t)e1 + 32) >> 6);
}
} // namespace

void
bcn_bc7_block(const uint8_t *blk, uint8_t out[64]) {
  BitReader br(blk);
  uint32_t mode = 0;
  while (mode < 8 && br.get(1) == 0) mode++;
  if (mode >= 8) {                 /* reserved: the spec mandates opaque black */
    memset(out, 0, 64);
    for (int t = 0; t < 16; t++) out[t * 4 + 3] = 255;
    return;
  }
  const Bc7Mode &m = kModes[mode];
  const uint32_t nep = (uint32_t)m.ns * 2;

  uint32_t part = m.pb ? br.get(m.pb) : 0;
  uint32_t rot  = m.rb ? br.get(m.rb) : 0;
  uint32_t isel = m.isb ? br.get(m.isb) : 0;

  uint8_t ep[6][4];
  uint32_t rawc[6][3], rawa[6];
  for (int c = 0; c < 3; c++) for (uint32_t e = 0; e < nep; e++) rawc[e][c] = br.get(m.cb);
  for (uint32_t e = 0; e < nep; e++) rawa[e] = m.ab ? br.get(m.ab) : 0;

  uint32_t pbit[6] = {0,0,0,0,0,0};
  if (m.epb) for (uint32_t e = 0; e < nep; e++) pbit[e] = br.get(1);
  else if (m.spb) for (uint32_t s = 0; s < m.ns; s++) {
    uint32_t p = br.get(1); pbit[s * 2] = pbit[s * 2 + 1] = p;
  }

  for (uint32_t e = 0; e < nep; e++) {
    uint32_t cb = m.cb, ab = m.ab;
    for (int c = 0; c < 3; c++) {
      uint32_t v = rawc[e][c];
      if (m.epb || m.spb) { v = (v << 1) | pbit[e]; ep[e][c] = expand(v, cb + 1); }
      else                 ep[e][c] = expand(v, cb);
    }
    if (ab) {
      uint32_t v = rawa[e];
      if (m.epb || m.spb) { v = (v << 1) | pbit[e]; ep[e][3] = expand(v, ab + 1); }
      else                 ep[e][3] = expand(v, ab);
    } else ep[e][3] = 255;
  }

  /* Index bits. The anchor index of each subset is stored one bit short. */
  uint8_t idx[16], idx2[16];
  const uint8_t *ptab = (m.ns == 2) ? kPart2[part] : (m.ns == 3 ? kPart3[part] : nullptr);
  uint32_t a1 = 0, a2 = 0;
  if (m.ns == 2) a1 = kAnchor2[part];
  else if (m.ns == 3) { a1 = kAnchor3a[part]; a2 = kAnchor3b[part]; }

  for (int t = 0; t < 16; t++) {
    uint32_t sub = ptab ? ptab[t] : 0;
    (void)sub;
    /* Subset 0's anchor is always texel 0; subsets 1 and 2 take theirs from the
     * anchor tables. An anchor's index is stored with one bit fewer because its
     * high bit is implied zero -- miscount this and every later index shifts. */
    bool anchor = (t == 0) || (m.ns >= 2 && (uint32_t)t == a1) || (m.ns == 3 && (uint32_t)t == a2);
    idx[t] = (uint8_t)br.get(anchor ? m.ib - 1u : m.ib);
  }
  if (m.ib2) {
    for (int t = 0; t < 16; t++)
      idx2[t] = (uint8_t)br.get((t == 0) ? m.ib2 - 1u : m.ib2);
  }

  const uint16_t *wc = (m.ib == 2) ? kW2 : (m.ib == 3 ? kW3 : kW4);
  const uint16_t *wa = (m.ib2 == 2) ? kW2 : (m.ib2 == 3 ? kW3 : kW4);

  for (int t = 0; t < 16; t++) {
    uint32_t sub = ptab ? ptab[t] : 0;
    const uint8_t *e0 = ep[sub * 2], *e1 = ep[sub * 2 + 1];
    uint8_t px[4];
    if (m.ib2) {
      /* two index sets: one drives colour, the other alpha, swapped by isel */
      const uint8_t ci = isel ? idx2[t] : idx[t];
      const uint8_t ai = isel ? idx[t]  : idx2[t];
      const uint16_t cw = isel ? wa[ci] : wc[ci];
      const uint16_t aw = isel ? wc[ai] : wa[ai];
      for (int c = 0; c < 3; c++) px[c] = interp(e0[c], e1[c], cw);
      px[3] = interp(e0[3], e1[3], aw);
    } else {
      for (int c = 0; c < 4; c++) px[c] = interp(e0[c], e1[c], wc[idx[t]]);
    }
    if (rot == 1)      { uint8_t v = px[0]; px[0] = px[3]; px[3] = v; }
    else if (rot == 2) { uint8_t v = px[1]; px[1] = px[3]; px[3] = v; }
    else if (rot == 3) { uint8_t v = px[2]; px[2] = px[3]; px[3] = v; }
    out[t * 4 + 0] = px[0]; out[t * 4 + 1] = px[1];
    out[t * 4 + 2] = px[2]; out[t * 4 + 3] = px[3];
  }
}

